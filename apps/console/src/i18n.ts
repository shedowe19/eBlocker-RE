export function initialLocale(): Locale {
    try {
        const saved = localStorage.getItem('eblocker.console.language');
        if (saved === 'de' || saved === 'en') return saved;
    } catch {
        /* Storage is optional. */
    }
    return navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en';
}
